"""Writes unicode_tables.h: the code point ranges of Unicode letters (L*) and numbers (N*), which the tokenizer's
GPT-2 pattern (\\p{L}, \\p{N}) needs. Run once: python3 phone/engine/gen_unicode.py"""
import sys
import unicodedata
from pathlib import Path


def ranges(pred):
    out, start = [], None
    for c in range(0x110000):
        if pred(unicodedata.category(chr(c))):
            if start is None:
                start = c
        elif start is not None:
            out.append((start, c - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def table(name, rs):
    body = ",".join(f"{{0x{a:X},0x{b:X}}}" for a, b in rs)
    return f"static const int {name}_N = {len(rs)};\nstatic const uint32_t {name}[][2] = {{{body}}};\n"


L = ranges(lambda c: c.startswith("L"))
N = ranges(lambda c: c.startswith("N"))
out = Path(__file__).with_name("unicode_tables.h")
out.write_text(f"// Generated by gen_unicode.py from Python {sys.version.split()[0]}'s Unicode {unicodedata.unidata_version} data.\n"
               "#pragma once\n#include <cstdint>\n" + table("UNI_L", L) + table("UNI_N", N))
print(out, len(L), len(N))
